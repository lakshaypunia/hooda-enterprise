/**
 * Writes docs/IMAGE_SOURCES.md: where each product's image came from and whether
 * the file actually exists in public/products/.
 *
 * Usage: npm run images:report
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { products } from "../data/products.ts";

type Source = { source: string; file: string; page: number; sourcePx: number };

const root = join(import.meta.dirname, "..");
const sources: Record<string, Source> = JSON.parse(
  readFileSync(join(root, "data/image-sources.json"), "utf-8"),
);

const LOW_RES_PX = 300;

const rows = products.map((p, i) => {
  const src = sources[p.slug];
  const file = `public/products/${p.slug}.webp`;
  const onDisk = existsSync(join(root, file));
  const origin = src ? `Hindi catalogue PDF, page ${src.page}` : "—";
  const notes = !src
    ? "No photo yet — placeholder shown"
    : src.sourcePx < LOW_RES_PX
      ? `Low resolution (${src.sourcePx}px original)`
      : "";
  return `| ${i + 1} | ${p.name} | ${origin} | ${onDisk ? `\`${file}\`` : "—"} | ${onDisk ? "✅" : "❌"} | Not downloaded | ${notes} |`;
});

const withImage = products.filter((p) => existsSync(join(root, `public/products/${p.slug}.webp`))).length;

const md = `# Product Image Sources

_Generated by \`npm run images:report\` — do not edit by hand._

**${withImage} of ${products.length}** products have an image on disk.
No images have been downloaded from the Provet website (provet.in); all photos are
extracted from \`Product Catalogue Hindi.pdf\` by \`scripts/extract-catalogue-images.py\`.

| # | Product | Image source | Local file | On disk | Provet website | Notes |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}
`;

writeFileSync(join(root, "docs/IMAGE_SOURCES.md"), md);
console.log(`docs/IMAGE_SOURCES.md — ${withImage}/${products.length} products with images`);
